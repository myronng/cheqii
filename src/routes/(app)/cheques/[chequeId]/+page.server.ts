    "whichPersonAreYou",
    "claimHint",
    "imNotListed",
    "thisIsMe",
    "thisIsYou",
    "changeWhichPersonIsYou",
    "linkedToYou",
    "cheque",
    "cheque{date}",
    "chequeName",
    "close",
    "person{index}",
    "cost",
    "customize",
    "customSplit",
    "splitEvenly",
    "settleUp",
    "{count}Recipients",
    "{count}Recipient",
    "{payer}Pays{payee}",
    "deleteCheque",
    "downloadCsv",
    "etransfer",
    "exportChequeDataToUseInOtherApplications",
    "home",
    "invited",
    "inviteLink",
    "item",
    "{item}Buyer",
    "{item}ContributionFrom{person}",
    "{item}Cost",
