    "remove{item}",
    "settings",
    "share",
    "signInWithGoogle",
    "offline",
    "subtotal",
    "syncError",
    "synced",
    "syncing",
    "theCurrentInvitationLinkWillNoLongerWork",
    "thisWillDeleteTheChequeForAllUsers",
    "total",
    "unlinkYourAccountFrom{payee}",
    "unsyncedChanges",
    "{user}(you)",
